    const Rows& rowsFor(wchar_t character)
    {
        const auto& glyphs = table();

        if (auto it = glyphs.find(character); it != glyphs.end())
            return it->second;

        const wchar_t upper = static_cast<wchar_t>(std::towupper(character));
        if (auto it = glyphs.find(upper); it != glyphs.end())
            return it->second;

        return blank();
    }

    bool isSupported(wchar_t character)
    {
        const auto& glyphs = table();
        if (glyphs.contains(character))
            return true;
        return glyphs.contains(static_cast<wchar_t>(std::towupper(character)));
    }
